import mongoose from "mongoose";

const PlanSchema = new mongoose.Schema({
  key:                     { type: String, required: true, unique: true },
  name:                    { type: String, required: true },
  label:                   { type: String },
  price:                   { type: Number, required: true },
  currency:                { type: String, default: "NGN" },
  period:                  { type: String, default: "month" },
  accentHex:               { type: String, default: "#3b82f6" },
  tagline:                 { type: String },

  // ── Kept for display/backward-compat — generated by admin UI ──
  messages:                { type: String },

  // ── NUMERIC LIMITS (all enforced as Number in backend) ─────────
  // "Monthly Message Quota" — total inbound + outbound WhatsApp messages
  messagesLimit:           { type: Number, default: 0 },

  // ── WhatsApp & Broadcast ───────────────────────────────────────
  whatsappNumbersLimit:    { type: Number, default: 1 },
  broadcastContactsLimit:  { type: Number, default: 0 },  // 0 = none; -1 = unlimited
  bulkSequences:           { type: Boolean, default: false },
  scheduledBroadcast:      { type: Boolean, default: false },
  segmentation:            { type: Boolean, default: false },
  campaignReports:         { type: Boolean, default: false },

  // ── Storefront & Commerce ──────────────────────────────────────
  storefrontEnabled:       { type: Boolean, default: true },
  productsLimit:           { type: Number, default: 20 },       // 0 = unlimited
  orderReceiptsEnabled:    { type: Boolean, default: true },
  salesAlertsEnabled:      { type: Boolean, default: true },
  salesAnalyticsEnabled:   { type: Boolean, default: false },
  salesAnalyticsDays:      { type: Number, default: 7 },        // 0 = unlimited history
  customStorefrontDomain:  { type: Boolean, default: false },

  // ── AI & Automation ────────────────────────────────────────────
  aiAgentEnabled:          { type: Boolean, default: true },
  leadFollowupEnabled:     { type: Boolean, default: false },
  leadQualificationEnabled:{ type: Boolean, default: false },
  productRecommendations:  { type: Boolean, default: false },

  // ── Branding & Team ────────────────────────────────────────────
  multiStaff:              { type: Number, default: 0 },        // 0 = owner only; -1 = unlimited
  whitelabel:              { type: Boolean, default: false },

  // ── Pricing & Billing ──────────────────────────────────────────
  extraMessagePrice:       { type: Number, default: 0 },
  referralReward:          { type: Number, default: 0 },

  // ── Display ────────────────────────────────────────────────────
  features:                [{ type: String }],
  popular:                 { type: Boolean, default: false },
  isActive:                { type: Boolean, default: true },

  // ── WhatsApp connection type ───────────────────────────────────
  connectionType: {
    type: String,
    enum: ["qr", "meta", "any"],
    default: "any",
  },

  // ── QR-specific limits ─────────────────────────────────────────
  dailyMessageLimit:   { type: Number, default: 200 },
  weeklyMessageLimit:  { type: Number, default: 0 },
  banRiskThreshold:    { type: Number, default: 500 },

}, { timestamps: true });

const PlanModel = mongoose.models.Plan || mongoose.model("Plan", PlanSchema);
export default PlanModel;
